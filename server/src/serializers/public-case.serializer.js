export function serializePublicCase(source) {
  return {
    id: source.id,
    title: source.title,
    summary: source.summary,
    incidentType: source.incidentType,
    setting: source.setting,
    incidentTime: source.incidentTime,
    difficulty: source.difficulty,
    playTimeMinutes: source.playTimeMinutes,
    status: source.status,
    createdAt: source.createdAt,
    suspects: source.suspects.map((suspect) => ({
      id: suspect.id,
      name: suspect.name,
      role: suspect.role,
      profile: suspect.profile,
      statedAlibi: suspect.statedAlibi,
      apparentMotive: suspect.apparentMotive,
    })),
    evidence: source.evidence.map((item) => ({
      id: item.id,
      title: item.title,
      type: item.type,
      timestamp: item.timestamp,
      description: item.description,
      content: structuredClone(item.content),
      sourceContext: item.sourceContext,
      relatedSuspectIds: [...item.relatedSuspectIds],
      relatedEventIds: [...item.relatedEventIds],
      reliability: item.reliability,
      reliabilityReason: item.reliabilityReason,
      fictionalLabel: item.fictionalLabel,
    })),
    timeline: source.timeline.map((event) => ({
      id: event.id,
      timestamp: event.timestamp,
      description: event.description,
      relatedSuspectIds: [...event.relatedSuspectIds],
      relatedEvidenceIds: [...event.relatedEvidenceIds],
      certainty: event.certainty,
    })),
  };
}
